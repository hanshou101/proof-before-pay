// Builds `vectors/golden.json` — the language-neutral replay vectors for AC-1 / AC-5.
//
// Run with `npm run vectors` (it builds `dist/` first). The script refuses to write the file
// unless every generated check matches `demo/scenario/scenario.json`'s golden values, so the
// vectors can never drift away from the normative scenario.
//
// A port to another language only needs this file: it contains the whole input context and
// the expected `CheckResult[]` / decision per item, facts included.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { evaluate, fingerprint, idempotencyKey } from '../dist/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const repo = join(root, '..', '..');

const scenario = JSON.parse(readFileSync(join(repo, 'demo/scenario/scenario.json'), 'utf8'));
const inboxContent = JSON.parse(readFileSync(join(repo, 'demo/scenario/inbox-content.json'), 'utf8'));

const EPOCH = 'ep_demo_2026_11_06';
const FIXED_SHA = 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855';

const emailFrom = (header) => {
  const match = /<([^<>]+)>/.exec(header);
  return (match?.[1] ?? header).trim();
};

const historyPrint = fingerprint({
  vendorId: 'ven_kenji',
  invoiceNumber: 'INV-0142',
  currency: 'USD',
  total: 115000,
});

const historyIntent = {
  id: 'hist_kenji_0142',
  itemId: 'hist_kenji_0142',
  vendorId: 'ven_kenji',
  agreementId: 'agr_kenji_11',
  amount: 115000,
  currency: 'USD',
  payee: { rail: 'paypal', recipientType: 'EMAIL', receiver: 'kenji@kenjimotion.example' },
  fingerprint: historyPrint,
  idempotencyKey: idempotencyKey(EPOCH, historyPrint),
  state: 'proven',
  at: '2026-11-02T09:15:00Z',
  transactionId: '7XK92134AB556677C',
};

const changeRequests = [
  {
    id: 'cr_ana_2207',
    vendorId: 'ven_ana',
    requestedPayee: 'billing@studi0-north.example',
    sourceItemId: 'in_04',
    requestedAt: '2026-11-04T21:47:00Z',
    status: 'unverified',
  },
];

const context = {
  vendors: scenario.vendors,
  agreements: scenario.agreements,
  deliveries: scenario.deliveries,
  changeRequests,
  intents: [historyIntent],
  history: [],
  policy: scenario.policy,
  now: scenario.testClock,
  epoch: EPOCH,
};

const claimOf = (item) => {
  const vendor = scenario.vendors.find((entry) => entry.id === item.claim.vendorId);
  const inboxItem = scenario.inbox.find((entry) => entry.id === item.itemId);
  return {
    itemId: item.itemId,
    vendorId: item.claim.vendorId,
    vendorName: vendor?.name ?? '',
    senderEmail: emailFrom(inboxItem.from),
    invoiceNumber: item.claim.invoiceNumber,
    issueDate: item.claim.issueDate,
    currency: item.claim.currency,
    total: item.claim.total,
    po: item.claim.po,
    requestedPayee: item.claim.requestedPayee,
    lines: item.claim.lines,
    sourceSha256: FIXED_SHA,
    extractedBy: null,
  };
};

const problems = [];
const cases = [];

for (const item of scenario.golden.items) {
  if (!item.claim || !item.checks) continue;
  const proposal = {
    claim: claimOf(item),
    agreementId: item.agreementId,
    agreementMatchedBy: item.agreementMatchedBy ?? 'po',
    rationale: 'golden vector',
  };
  const { checks, decision } = evaluate(proposal, context);

  for (const check of checks) {
    const golden = item.checks[check.id];
    const [status, code] = golden.split(':');
    if (check.status !== status) {
      problems.push(`${item.itemId} ${check.id}: status ${check.status} != golden ${status}`);
    }
    if (code && check.code !== code) {
      problems.push(`${item.itemId} ${check.id}: code ${check.code} != golden ${code}`);
    }
  }
  if (decision !== item.decision) {
    problems.push(`${item.itemId}: decision ${decision} != golden ${item.decision}`);
  }

  cases.push({ itemId: item.itemId, proposal, checks, decision });
}

if (problems.length > 0) {
  console.error('Golden mismatches — refusing to write vectors:\n' + problems.map((p) => `  ${p}`).join('\n'));
  process.exit(1);
}

const vectors = {
  $comment:
    'AC-1 / AC-5 replay vectors for @pbp/core. Generated by packages/core/scripts/build-vectors.mjs from demo/scenario/*.json; do not hand-edit. Replaying a port: build the context from vendors/agreements/deliveries/changeRequests/intents/history/policy at testClock, call evaluate(proposal), and compare CheckResult arrays (facts included) and the decision.',
  spec: 'docs/01-SPEC.md §6.2–§6.3',
  version: '1.0.0',
  testClock: scenario.testClock,
  epoch: EPOCH,
  policy: scenario.policy,
  vendors: scenario.vendors,
  agreements: scenario.agreements,
  deliveries: scenario.deliveries,
  changeRequests,
  intents: [historyIntent],
  history: [],
  cases,
};

writeFileSync(join(root, 'vectors/golden.json'), JSON.stringify(vectors, null, 2) + '\n', 'utf8');
console.log(`wrote vectors/golden.json with ${cases.length} cases`);
